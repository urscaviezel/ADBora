    /// <summary>16×16 grey values of the icon composited on mid-grey; null if it cannot be decoded.</summary>
    public static byte[]? Fingerprint(byte[] icon)
    {
        using SKBitmap? bmp = ImageLoader.Decode(icon);
        if (bmp is null) return null;
        using var big = new SKBitmap(new SKImageInfo(64, 64, SKColorType.Bgra8888, SKAlphaType.Premul));
        using (var canvas = new SKCanvas(big))
        {
            canvas.Clear(new SKColor(128, 128, 128));
            using SKImage img = SKImage.FromBitmap(bmp);
            canvas.DrawImage(img, new SKRect(0, 0, 64, 64), new SKSamplingOptions(SKFilterMode.Linear, SKMipmapMode.Linear));
        }
        // box filter 64 → 16 (independent of Skia's down-sampling details)
        var print = new byte[Size * Size];
        for (int y = 0; y < Size; y++)
            for (int x = 0; x < Size; x++)
            {
                double sum = 0;
                for (int dy = 0; dy < 4; dy++)
                    for (int dx = 0; dx < 4; dx++)
                    {
                        SKColor c = big.GetPixel(x * 4 + dx, y * 4 + dy);
                        sum += 0.299 * c.Red + 0.587 * c.Green + 0.114 * c.Blue;
                    }
                print[y * Size + x] = (byte)Math.Round(sum / 16);
            }
        return print;
    }

    public static double Distance(byte[] a, byte[] b)
    {
        double sum = 0;
        for (int i = 0; i < a.Length; i++) sum += Math.Abs(a[i] - b[i]);
        return sum / a.Length;
    }

    /// <summary>Kind of placeholder ("unity", "unreal", "android") or null for a real icon.</summary>
    public static string? Detect(byte[] icon)
    {
        if (icon.Length == 0 || References.Length == 0) return null;
        byte[]? print = Fingerprint(icon);
        if (print is null) return null;
        (string Kind, double D) best = References.Select(r => (r.Kind, Distance(print, r.Print))).MinBy(r => r.Item2);
        return best.D < Threshold ? best.Kind : null;
    }
